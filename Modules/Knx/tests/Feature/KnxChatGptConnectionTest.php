    // ---- refresh --------------------------------------------------------------------

    public function test_refresh_rotates_access_refresh_expiry_and_scopes_together(): void
    {
        $this->signIn(['access_token' => 'access-1', 'refresh_token' => 'refresh-1', 'expires_in' => 60])->assertOk();
        $connection = KnxChatGptConnection::query()->sole();
        $before = $connection->access_expires_at;

        $this->tokenHandler = fn (Request $r) => Http::response([
            'access_token' => 'access-2',
            'refresh_token' => 'refresh-2',
            'expires_in' => 3600,
            'scope' => 'openid profile email offline_access resource.invoke',
            'token_type' => 'Bearer',
        ]);

        $fresh = app(ChatGptConnections::class)->refresh($connection);

        $this->assertSame('access-2', $fresh->access_token);
        $this->assertSame('refresh-2', $fresh->refresh_token);
        $this->assertTrue($fresh->access_expires_at->greaterThan($before));
        $this->assertSame(['openid', 'profile', 'email', 'offline_access', 'resource.invoke'], $fresh->scopes);
        $this->assertFalse((bool) $fresh->plan_permission);
        $this->assertSame('connected', $fresh->status);

        $body = $this->tokenRequests()[1]->data();
        $this->assertSame('refresh_token', $body['grant_type']);
        $this->assertSame('refresh-1', $body['refresh_token']);
        $this->assertSame(self::CLIENT_ID, $body['client_id']);

        $this->assertSame('access-2', KnxChatGptConnection::query()->sole()->access_token);
    }

    public function test_a_terminal_refresh_error_needs_a_new_sign_in_and_drops_the_tokens_but_keeps_the_identity(): void
    {
        foreach (['invalid_grant', 'invalid_refresh_token', 'refresh_token_expired', 'refresh_token_invalidated', 'refresh_token_reused', 'token_expired'] as $error) {
            DB::table('knx_chatgpt_connections')->delete();
            $this->signIn()->assertOk();
            $connection = KnxChatGptConnection::query()->sole();

            $this->tokenHandler = fn () => Http::response(['error' => $error], 400);

            try {
                app(ChatGptConnections::class)->refresh($connection);
                $this->fail("{$error} should fail the refresh");
            } catch (ChatGptFailed $e) {
                $this->assertSame('needs_sign_in', $e->reason, $error);
            }

            $row = KnxChatGptConnection::query()->sole();
            $this->assertSame('needs_sign_in', $row->status, $error);
            $this->assertNull($row->access_token);
            $this->assertNull($row->refresh_token);
            $this->assertFalse((bool) $row->plan_permission);
            $this->assertSame('lien@example.test', $row->email);

            $this->getJson('/api/v1/knx/chatgpt/connection')
                ->assertOk()
                ->assertJsonPath('connected', false)
                ->assertJsonPath('status', 'needs_sign_in')
                ->assertJsonPath('planPermission', false)
                ->assertJsonPath('identity.email', 'lien@example.test');
        }
    }

