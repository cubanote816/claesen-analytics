    // ---- start ----------------------------------------------------------------------

    public function test_start_builds_the_documented_authorization_url(): void
    {
        $url = $this->postJson('/api/v1/knx/chatgpt/connection/start')->assertOk()->json('authorizationUrl');

        $this->assertStringStartsWith('https://auth.openai.com/api/accounts/authorize?', $url);
        parse_str((string) parse_url($url, PHP_URL_QUERY), $query);

        $this->assertEqualsCanonicalizing(
            ['client_id', 'redirect_uri', 'response_type', 'scope', 'resource', 'state', 'nonce', 'code_challenge', 'code_challenge_method'],
            array_keys($query),
        );
        $this->assertSame(self::CLIENT_ID, $query['client_id']);
        $this->assertSame(self::REDIRECT, $query['redirect_uri']);
        $this->assertSame('code', $query['response_type']);
        $this->assertSame(self::PLAN_SCOPE, $query['scope']);
        $this->assertSame('https://api.openai.com/v1', $query['resource']);
        $this->assertSame('S256', $query['code_challenge_method']);
        $this->assertGreaterThanOrEqual(32, strlen($query['state']));
        $this->assertGreaterThanOrEqual(32, strlen($query['nonce']));
        $this->assertNotSame($query['state'], $query['nonce']);

        $second = $this->postJson('/api/v1/knx/chatgpt/connection/start')->json('authorizationUrl');
        parse_str((string) parse_url($second, PHP_URL_QUERY), $again);
        $this->assertNotSame($query['state'], $again['state']);
        $this->assertNotSame($query['code_challenge'], $again['code_challenge']);
    }

