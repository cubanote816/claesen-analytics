    public function test_missing_unknown_reused_expired_and_foreign_states_are_rejected_without_a_token_request(): void
    {
        $call = fn (array $body) => $this->postJson('/api/v1/knx/chatgpt/connection/callback', $body + ['code' => 'the-code']);

        // Missing.
        $call([])->assertStatus(422)->assertJsonPath('code', 'chatgpt_state_invalid');
        // Never issued.
        $call(['state' => 'made-up'])->assertStatus(422)->assertJsonPath('code', 'chatgpt_state_invalid');

        // Reused: the first callback consumes it, the second finds nothing.
        $this->signIn()->assertOk();
        DB::table('knx_chatgpt_connections')->delete();
        $used = $this->lastState;
        $requestsBefore = count($this->tokenRequests());
        $call(['state' => $used])->assertStatus(422)->assertJsonPath('code', 'chatgpt_state_invalid');

        // Expired (10 minutes).
        $expired = $this->start()['state'];
        $this->travel(11)->minutes();
        $call(['state' => $expired])->assertStatus(422)->assertJsonPath('code', 'chatgpt_state_invalid');
        $this->travelBack();

        // Another employee's state.
        $theirs = $this->start()['state'];
        $this->actAs('pieter.aerts@electrobertels.be');
        $call(['state' => $theirs])->assertStatus(422)->assertJsonPath('code', 'chatgpt_state_invalid');
        $this->actAs('lien.smet@electrobertels.be');
        $call(['state' => $theirs])->assertStatus(422);

        $this->assertSame(0, KnxChatGptConnection::query()->count());
        $this->assertCount($requestsBefore, $this->tokenRequests());
    }

