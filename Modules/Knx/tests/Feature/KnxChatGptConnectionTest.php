    private function actAs(string $email): void
    {
        $this->actingAs(User::query()->where('email', $email)->sole(), 'sanctum');
    }

    private function employee(string $email): KnxEmployee
    {
        return KnxEmployee::query()->where('user_id', User::query()->where('email', $email)->value('id'))->sole();
    }

    /** @return array{state: string, nonce: string, challenge: string} */
    private function start(): array
    {
        $url = $this->postJson('/api/v1/knx/chatgpt/connection/start')->assertOk()->json('authorizationUrl');
        parse_str((string) parse_url($url, PHP_URL_QUERY), $query);

        $this->lastState = $query['state'];
        $this->lastChallenge = $query['code_challenge'];

        return ['state' => $query['state'], 'nonce' => $query['nonce'], 'challenge' => $query['code_challenge']];
    }

    /**
     * Start, answer the token endpoint with a (by default valid) response, post the callback.
     *
     * @param  array<string, mixed>  $token  overrides of the token response (`id_token => false` omits it)
     * @param  array<string, mixed>  $claims  overrides of the ID-token claims (null removes one)
     */
    private function signIn(array $token = [], array $claims = [], string $signWith = 'main'): TestResponse
    {
        $start = $this->start();

        $this->tokenHandler = function () use ($token, $claims, $signWith, $start) {
            $claims = array_filter($claims + [
                'iss' => self::ISSUER,
                'aud' => self::CLIENT_ID,
                'sub' => 'sub-lien',
                'email' => 'lien@example.test',
                'name' => 'Lien Smet',
                'nonce' => $start['nonce'],
                'iat' => time(),
                'exp' => time() + 600,
            ], fn ($value) => $value !== null);

            $idToken = $this->signed($claims, $signWith === 'main' ? $this->key() : $this->otherKey());

            return Http::response(array_filter($token + [
                'access_token' => 'access-token',
                'refresh_token' => 'refresh-token',
                'token_type' => 'Bearer',
                'expires_in' => 3600,
                'scope' => self::PLAN_SCOPE,
                'id_token' => $idToken,
            ], fn ($value) => $value !== false));
        };

        return $this->postJson('/api/v1/knx/chatgpt/connection/callback', ['state' => $start['state'], 'code' => 'the-code']);
    }

    /** @return list<Request> */
    private function tokenRequests(): array
    {
        $requests = [];
        foreach (Http::recorded() as [$request]) {
            if ($request->url() === self::TOKEN_URL) {
                $requests[] = $request;
            }
        }

        return $requests;
    }

    private function fakeProvider(): void
    {
        Http::preventStrayRequests();
        Http::fake(function (Request $request) {
            return match ($request->url()) {
                'https://auth.openai.com/.well-known/openid-configuration' => Http::response([
                    'issuer' => self::ISSUER,
                    'authorization_endpoint' => 'https://auth.openai.com/api/accounts/authorize',
                    'token_endpoint' => self::TOKEN_URL,
                    'jwks_uri' => 'https://auth.openai.com/.well-known/jwks.json',
                ]),
                'https://auth.openai.com/.well-known/jwks.json' => Http::response(['keys' => [[
                    'kty' => 'RSA', 'use' => 'sig', 'alg' => 'RS256', 'kid' => self::KID,
                    'n' => $this->key()['n'], 'e' => $this->key()['e'],
                ]]]),
                self::TOKEN_URL => $this->tokenHandler === null
                    ? Http::response(['error' => 'unexpected'], 500)
                    : ($this->tokenHandler)($request),
                default => throw new \LogicException('Unexpected request to '.$request->url()),
            };
        });
    }

    /** @param  array<string, mixed>  $claims */
    private function signed(array $claims, array $key): string
    {
        return JWT::encode($claims, $key['pem'], 'RS256', self::KID);
    }

    /** @return array{pem: string, n: string, e: string} */
    private function key(): array
    {
        return self::$key ??= $this->generateKey();
    }

    /** @return array{pem: string, n: string, e: string} */
    private function otherKey(): array
    {
        return self::$otherKey ??= $this->generateKey();
    }

    /** @return array{pem: string, n: string, e: string} */
    private function generateKey(): array
    {
        $resource = openssl_pkey_new(['private_key_bits' => 2048, 'private_key_type' => OPENSSL_KEYTYPE_RSA]);
        openssl_pkey_export($resource, $pem);
        $rsa = openssl_pkey_get_details($resource)['rsa'];
        $b64 = fn (string $raw): string => rtrim(strtr(base64_encode($raw), '+/', '-_'), '=');

        return ['pem' => $pem, 'n' => $b64($rsa['n']), 'e' => $b64($rsa['e'])];
    }
}
